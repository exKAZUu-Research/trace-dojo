import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { PUBLIC_MODULES } from '../src/haskell/library';

/** The packages GHC 9.14.1 ships whose modules this environment provides, at the versions it ships. */
const PACKAGES = ['base-4.22.0.0', 'containers-0.8', 'template-haskell-2.24.0.0'];

interface ModuleExports {
  /** Each exported name, `v:` for a value and `t:` for a type or class, with the module that defines it. */
  origins: Map<string, string>;
  fields: Set<string>;
  /** Each type and class with the constructors, fields, methods and associated types GHC exports with it. */
  children: Map<string, Set<string>>;
}

const output = fileURLToPath(new URL('../src/haskell/library/ghcExports.ts', import.meta.url));
const pages = new Map<string, Promise<string>>();

await generate();

async function generate(): Promise<void> {
  const modules = new Map<string, ModuleExports>();
  // Data.Kind's kinds are built into the compiler rather than selected from the library.
  for (const name of [...Object.keys(PUBLIC_MODULES), 'Data.Kind']) {
    const exports = await moduleExports(name);
    if (exports) modules.set(name, exports);
    else console.info(`Skipped ${name}, which no package has`);
  }
  // Only a name that modules define differently needs its origin to tell which of them a module exports.
  const originsOf = new Map<string, Set<string>>();
  for (const exports of modules.values()) {
    for (const [key, origin] of exports.origins) originsOf.set(key, (originsOf.get(key) ?? new Set()).add(origin));
  }
  const lines = [...modules].map(([name, exports]) => {
    const keys = [...exports.origins.keys()];
    const names = (space: string): string[] =>
      keys.filter((key) => key.startsWith(space)).map((key) => key.slice(space.length));
    const types = names('t:')
      .toSorted(compare)
      .map((type) => `${JSON.stringify(type)}: ${literal(sorted(exports.children.get(type) ?? []))}`);
    const origins = keys
      .filter((key) => (originsOf.get(key)?.size ?? 0) > 1)
      .toSorted(compare)
      .map((key) => `${JSON.stringify(key)}: ${literal(exports.origins.get(key) ?? '')}`);
    const optional = [
      exports.fields.size > 0 ? `fields: ${literal(sorted(exports.fields))}` : '',
      origins.length > 0 ? `origins: { ${origins.join(', ')} }` : '',
    ].filter(Boolean);
    return `  ${JSON.stringify(name)}: { ${[`values: ${literal(sorted(names('v:')))}`, ...optional, `types: { ${types.join(', ')} }`].join(', ')} },`;
  });
  writeFileSync(
    output,
    `// Generated by scripts/generateHaskellGhcExports.ts from the Haddock documentation on Hackage of ${PACKAGES.join(', ')}, the versions GHC 9.14.1 ships.

/** A module's exports in GHC, each list of names separated by spaces. */
export interface GhcModuleExports {
  /** Its values, the constructors, fields and methods among them. */
  values: string;
  fields?: string;
  /** Its types and classes, each with the constructors, fields, methods and associated types it exports with them. */
  types: Record<string, string>;
  /** The defining module of each name (\`v:\` for a value, \`t:\` for a type) that other modules define differently. */
  origins?: Record<string, string>;
}

/** The names each module this environment provides exports in GHC 9.14.1. */
export const GHC_EXPORTS: Record<string, GhcModuleExports> = {
${lines.join('\n')}
};
`
  );
  execFileSync('bun', ['wb', 'lint', '--format', output], { stdio: 'inherit' });
}

async function moduleExports(name: string): Promise<ModuleExports | undefined> {
  for (const pkg of PACKAGES) {
    const url = `https://hackage.haskell.org/package/${pkg}/docs/${name.replaceAll('.', '-')}.html`;
    const html = await fetchPage(url);
    if (html !== undefined) return parsePage(html, url);
  }
  return undefined;
}

/** Reads a module's Haddock page: each top-level declaration, with the definitions inside it as its children. */
async function parsePage(html: string, url: string): Promise<ModuleExports> {
  const exports: ModuleExports = { origins: new Map(), fields: new Set(), children: new Map() };
  const body = html.slice(html.indexOf('<div id="interface">'));
  for (const block of body.split('<div class="top">').slice(1)) {
    const reexported = /^<p class="src">module <a href="([^"]+)"/.exec(block);
    if (reexported) {
      const inner = await parseModule(new URL(reexported[1], url).href);
      for (const [key, origin] of inner.origins) exports.origins.set(key, origin);
      for (const field of inner.fields) exports.fields.add(field);
      for (const [type, children] of inner.children) exports.children.set(type, children);
    } else {
      addDeclaration(exports, block, url);
    }
  }
  return exports;
}

async function parseModule(url: string): Promise<ModuleExports> {
  const html = await fetchPage(url);
  if (html === undefined) throw new Error(`Missing re-exported module ${url}`);
  return parsePage(html, url);
}

function addDeclaration(exports: ModuleExports, block: string, url: string): void {
  const origin = /href="(?:[^"]*\/)?src\/([^"/]+)\.html#[^"]*" class="link">Source</.exec(block)?.[1];
  const definitions = [
    ...withoutInstances(block).matchAll(
      /(<dfn class="src">)?(?:<span class="keyword">pattern<\/span> )?<a id="([tv]):([^"]+)" class="def"/g
    ),
  ].map((match) => ({ field: !!match[1], key: `${match[2]}:${decode(match[3])}` }));
  if (!origin || definitions.length === 0) throw new Error(`A declaration of ${url} without a definition or source`);
  const [top, ...children] = definitions;
  for (const { key } of definitions) exports.origins.set(key, origin);
  if (top.key.startsWith('v:')) return;
  const own = new Set(children.map((child) => child.key.slice(2)));
  exports.children.set(top.key.slice(2), own);
  for (const child of children) if (child.field) exports.fields.add(child.key.slice(2));
}

/** A declaration without its instances, whose data family instances define constructors the module does not export. */
function withoutInstances(block: string): string {
  const marker = '<div class="subs instances">';
  let rest = block;
  for (let start = rest.indexOf(marker); start !== -1; start = rest.indexOf(marker)) {
    let depth = 0;
    const tags = /<div\b|<\/div>/g;
    tags.lastIndex = start;
    for (let tag = tags.exec(rest); tag; tag = tags.exec(rest)) {
      depth += tag[0] === '</div>' ? -1 : 1;
      if (depth === 0) {
        rest = rest.slice(0, start) + rest.slice(tags.lastIndex);
        break;
      }
    }
    if (depth !== 0) throw new Error('An unclosed list of instances');
  }
  return rest;
}

async function fetchPage(url: string): Promise<string | undefined> {
  let page = pages.get(url);
  if (!page) {
    page = fetch(url).then(async (response) => {
      if (response.status === 404) return '';
      if (!response.ok) throw new Error(`${url}: ${response.status}`);
      return response.text();
    });
    pages.set(url, page);
  }
  return (await page) || undefined;
}

/** Haddock's anchors spell some characters of a name, those of an operator among them, as `-<code point>-`. */
function decode(anchor: string): string {
  return anchor.replaceAll(/-(\d+)-/g, (_, code: string) => String.fromCodePoint(Number(code)));
}

/** A string literal, raw when it has a backslash, as lint requires; no Haskell name has a backtick or `${`. */
function literal(text: string): string {
  return text.includes('\\') ? `String.raw\`${text}\`` : JSON.stringify(text);
}

function sorted(names: Iterable<string>): string {
  return [...names].toSorted(compare).join(' ');
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}
