import _sre

LIMIT = 0x110000
DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'


def base36(number):
    if number < 0:
        return '-' + base36(-number)
    text = ''
    while True:
        text = DIGITS[number % 36] + text
        number //= 36
        if number == 0:
            return text


def encode_set(predicate):
    parts = []
    previous = 0
    start = None
    for code in range(LIMIT + 1):
        inside = code < LIMIT and predicate(code)
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            parts += [base36(start - previous), base36(code - start)]
            previous = code
            start = None
    return ','.join(parts)


def encode_map(mapping):
    entries = [(code, mapping(code) - code) for code in range(LIMIT) if mapping(code) != code]
    parts = []
    previous = 0
    index = 0
    while index < len(entries):
        code, delta = entries[index]
        count, stride = 1, 1
        for candidate in (1, 2):
            end = index
            while (
                end + 1 < len(entries)
                and entries[end + 1][0] == entries[end][0] + candidate
                and entries[end + 1][1] == delta
            ):
                end += 1
            if end - index + 1 > count:
                count, stride = end - index + 1, candidate
        parts.append(':'.join([base36(code - previous), base36(count), base36(stride), base36(delta)]))
        previous = code + (count - 1) * stride + 1
        index += count
    return ','.join(parts)


