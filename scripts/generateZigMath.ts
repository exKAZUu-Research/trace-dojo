import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { binaryOperations, unaryOperations } from '../src/zig/referenceMathOperations';

const root = fileURLToPath(new URL('../', import.meta.url));
const zig = process.argv[2] ?? 'zig';

generate();

function generate(): void {
  assert.equal(run(['version']).trim(), '0.17.1');
  mkdirSync(join(root, '.tmp'), { recursive: true });
  const directory = mkdtempSync(join(root, '.tmp/zigMath-'));
  try {
    const source = join(directory, 'math.zig');
    const binary = join(directory, 'math.wasm');
    writeFileSync(source, buildSource());
    run([
      'build-exe',
      source,
      '-target',
      'wasm32-freestanding',
      '-fno-entry',
      '-rdynamic',
      '-O',
      'ReleaseSafe',
      '-fstrip',
      `-femit-bin=${binary}`,
      '--cache-dir',
      join(directory, 'cache'),
      '--global-cache-dir',
      join(directory, 'global'),
    ]);
    const bytes = readFileSync(binary);
    const module = new WebAssembly.Module(new Uint8Array(bytes));
    assert.deepEqual(WebAssembly.Module.imports(module), []);
    writeFileSync(
      join(root, 'src/zig/referenceMathBytes.ts'),
      `// Generated by scripts/generateZigMath.ts with Zig 0.17.1.\nexport const referenceMathBytes = '${bytes.toString('base64')}';\n`
    );
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

function buildSource(): string {
  const wrappers = [
    ...Object.entries(unaryOperations).map(([name, domain]) => wrappersFor(name, domain, false)),
    ...Object.entries(binaryOperations).map(([name, domain]) => wrappersFor(name, domain, true)),
  ].join('\n');
  return `const std = @import("std");
var result: u128 = 0;
${wrappers}
export fn resultLow() u64 { return @truncate(result); }
export fn resultHigh() u64 { return @truncate(result >> 64); }
fn fromWords(comptime T: type, lo: u64, hi: u64) T {
    const U = if (@bitSizeOf(T) == 80) u80 else u128;
    return @bitCast(@as(U, @truncate(@as(u128, lo) | (@as(u128, hi) << 64))));
}
fn store(comptime T: type, value: T) void {
    const U = if (@bitSizeOf(T) == 80) u80 else u128;
    result = @as(U, @bitCast(value));
}
`;
}

function wrappersFor(name: string, domain: 'all' | 'narrow', binary: boolean): string {
  const widths = domain === 'all' ? [16, 32, 64, 80, 128] : [32, 64];
  return widths
    .map((bits) => {
      const type = `f${bits}`;
      const call = mathCall(name, type, binary);
      if (bits > 64)
        return `export fn ${name}${bits}(xlo: u64, xhi: u64${binary ? ', ylo: u64, yhi: u64' : ''}) void {
    const x = fromWords(${type}, xlo, xhi);
    ${binary ? `const y = fromWords(${type}, ylo, yhi);` : ''}
    store(${type}, ${call});
}`;
      const abi = bits === 16 ? 'f32' : type;
      return `export fn ${name}${bits}(a: ${abi}${binary ? `, b: ${abi}` : ''}) ${abi} {
    const x: ${type} = @floatCast(a);
    ${binary ? `const y: ${type} = @floatCast(b);` : ''}
    return ${call};
}`;
    })
    .join('\n');
}

function mathCall(name: string, type: string, binary: boolean): string {
  if (name === 'logBase' || name === 'pow') {
    const callee = name === 'logBase' ? 'log' : name;
    return `std.math.${callee}(${type}, x, y)`;
  }
  return name === 'log' ? '@log(x)' : `std.math.${name}(x${binary ? ', y' : ''})`;
}

function run(args: readonly string[]): string {
  const result = spawnSync(zig, args, { cwd: root, encoding: 'utf8' });
  assert.equal(result.status, 0, result.error?.message ?? result.stderr);
  return result.stdout;
}
