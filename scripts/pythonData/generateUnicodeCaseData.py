import sys
import unicodedata

from unicode_runs import print_property, runs

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

CODES = range(sys.maxunicode + 1)


def is_case_ignorable(char):
    # str exposes Case_Ignorable only through the final sigma rule of lower(): a sigma after a cased letter is final,
    # and lower() looks past case-ignorable characters for that letter.
    after_cased = ('A' + char + 'Σ').lower().endswith('ς')
    after_char = (char + 'Σ').lower().endswith('ς')
    return after_cased and not after_char


CLASSES = {
    'isUpper': str.isupper,
    'isLower': str.islower,
    'isTitle': lambda char: unicodedata.category(char) == 'Lt',
    'isCased': lambda char: char.isupper() or char.islower() or unicodedata.category(char) == 'Lt',
    'isCaseIgnorable': is_case_ignorable,
}


def mapping(convert):
    """
    The code points that the conversion changes: runs of "offset,count,step,delta" in hexadecimal for one-character
    results, where the offset is from the previous run's last code point, then "code:result" for longer ones.
    """
    single = {}
    special = []
    for code in CODES:
        result = convert(chr(code))
        if len(result) > 1:
            special.append(f'{code:x}:' + ' '.join(f'{ord(char):x}' for char in result))
        elif result != chr(code):
            single[code] = ord(result) - code
    runs = []
    last = 0
    codes = sorted(single)
    index = 0
    while index < len(codes):
        start = codes[index]
        delta = single[start]
        step = 1
        count = 1
        for candidate in (1, 2):
            if single.get(start + candidate) == delta:
                step = candidate
                break
        while single.get(start + count * step) == delta:
            count += 1
        runs.append(f'{start - last:x},{count:x},{step:x},{delta:x}')
        last = start + (count - 1) * step
        index = codes.index(last, index) + 1
    return ';'.join(runs), ';'.join(special)


print(f'// Generated by scripts/pythonData/generateUnicodeCaseData.py from CPython 3.14.10 (Unicode '
      f'{unicodedata.unidata_version}); do not edit.')
print('// Each mapping is runs of "offset,count,step,delta" for one-character results and "code:result" for longer '
      'ones.')
print('export const CASE_DATA = {')
for name, convert in (('upper', str.upper), ('lower', str.lower), ('title', str.title), ('fold', str.casefold)):
    mapped, special = mapping(convert)
    print(f'  {name}: [')
    print(f"    '{mapped}',")
    print(f"    '{special}',")
    print('  ],')
for name, test in CLASSES.items():
    print_property(name, runs(test))
print('} as const;')
