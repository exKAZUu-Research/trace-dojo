# Prints src/python/data/japaneseCodecs.ts: the JIS tables of CPython's Japanese codecs, read back from the codecs:
#   mise exec -- python scripts/pythonData/generateJapaneseCodecs.py > src/python/data/japaneseCodecs.ts
import sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')


def kuten_row(decode, row):
    """The 94 characters of a JIS row, with a space for each unassigned cell."""
    chars = []
    for cell in range(1, 95):
        try:
            text = decode(row, cell)
        except UnicodeDecodeError:
            text = ' '
        assert len(text) == 1
        chars.append(text)
    return ''.join(chars)


def euc0208(row, cell):
    return bytes([row + 0xA0, cell + 0xA0]).decode('euc_jp')


def euc0212(row, cell):
    return bytes([0x8F, row + 0xA0, cell + 0xA0]).decode('euc_jp')


def sjis_bytes(row, cell):
    lead = (row + 1) // 2 + (0x80 if row <= 62 else 0xC0)
    if row % 2:
        trail = cell + (0x3F if cell <= 63 else 0x40)
    else:
        trail = cell + 0x9E
    return bytes([lead, trail])


def cp932(row, cell):
    return sjis_bytes(row, cell).decode('cp932')


def rows_literal(name, doc, decode, first, last):
    lines = [f'/** {doc} */', f'export const {name} = [']
    for row in range(first, last + 1):
        text = kuten_row(decode, row)
        assert "'" not in text and '\\' not in text
        escaped = ''.join(char if char.isprintable() else f'\\u{ord(char):04x}' for char in text)
        lines.append(f"  '{escaped}',")
    lines.append("].join('');")
    return '\n'.join(lines)


print('// Generated by scripts/pythonData/generateJapaneseCodecs.py from CPython 3.14; do not edit.')
print('// Each string holds the characters of consecutive 94-cell rows, a space standing for an unassigned cell.')
print()
print(rows_literal('JIS_X_0208', 'Rows 1 to 84 of JIS X 0208, as euc_jp, shift_jis, and iso2022_jp decode them.', euc0208, 1, 84))
print()
print(rows_literal('JIS_X_0212', 'Rows 2 to 77 of JIS X 0212, which euc_jp writes after the byte 0x8F.', euc0212, 2, 77))
print()
print(rows_literal('CP932_ROW_13', 'Row 13 of cp932, the NEC special characters.', cp932, 13, 13))
print()
print(rows_literal('CP932_ROWS_89_TO_92', 'Rows 89 to 92 of cp932, the NEC-selected IBM extensions.', cp932, 89, 92))
print()
print(rows_literal('CP932_ROWS_115_TO_119', 'Rows 115 to 119 of cp932, the IBM extensions.', cp932, 115, 119))
print()
changed = []
for row in (1, 2):
    for cell in range(1, 95):
        try:
            a = euc0208(row, cell)
        except UnicodeDecodeError:
            a = None
        try:
            b = cp932(row, cell)
        except UnicodeDecodeError:
            b = None
        if a != b:
            point = ord(b)
            changed.append(f'  [{(row - 1) * 94 + cell - 1}, 0x{point >> 8:02x}_{point & 0xFF:02x}],')
print('/** The cells of JIS X 0208 rows 1 and 2 that cp932 decodes differently, by index from row 1 cell 1. */')
print('export const CP932_CHANGES: [number, number][] = [')
print('\n'.join(changed))
print('];')
