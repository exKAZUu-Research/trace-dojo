# Prints src/python/modules/randomSource.ts: CPython's random.py, which this grader runs over its native `_random`, with
# the imports it cannot make deferred to their use and without its test program, fork support, and command line:
#   mise exec -- python scripts/pythonData/generateRandomSource.py > src/python/modules/randomSource.ts
import os
import sys
import sysconfig

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

with open(os.path.join(sysconfig.get_paths()['stdlib'], 'random.py'), encoding='utf-8') as file:
    source = file.read()


def replace(old, new):
    global source
    assert source.count(old) == 1, old
    source = source.replace(old, new)


# math.lgamma, which this grader does not have, is needed only by binomialvariate; _urandom is a native.
replace(
    'from math import lgamma as _lgamma, fabs as _fabs, log2 as _log2\nfrom os import urandom as _urandom\n',
    'from math import fabs as _fabs, log2 as _log2\n\n\n'
    'def _lgamma(x):\n    from math import lgamma\n    return lgamma(x)\n\n\n',
)
replace('import os as _os\n', '')
replace(
    """                try:
                    # hashlib is pretty heavy to load, try lean internal
                    # module first
                    from _sha2 import sha512 as _sha512
                except ImportError:
                    # fallback to official implementation
                    from hashlib import sha512 as _sha512
""",
    """                from hashlib import sha512 as _sha512
""",
)
# The module's functions are the natives bound to _inst's generator, which give the same values faster.
end = source.index('## ------------------------------------------------------\n## ----------------- test program')
source = source[:end] + '_bind_natives(globals(), _inst)\ndel _bind_natives\n'

print('// Generated by scripts/pythonData/generateRandomSource.py from CPython 3.14; do not edit.')
print("/** CPython's `random.py`, with the imports this grader cannot make deferred to their use. */")
print('export const RANDOM_SOURCE = String.raw`' + source.replace('${', "${'$'}{").replace('`', "${'`'}") + '`;')
