# Prints src/python/data/jisX0213.ts: the two planes of JIS X 0213:2004, as CPython's shift_jis_2004 codec decodes
# and encodes them:
#   mise exec -- python scripts/pythonData/generateJisX0213.py > src/python/data/jisX0213.ts
#
# Each plane is a string of 94 rows of 94 cells, U+FFFF standing for a cell that decodes to nothing. The cells that
# decode to two characters and the characters that do not encode to the last cell that decodes to them are listed
# apart.
import sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

UNASSIGNED = '￿'


def number(value):
    """A number as the linter wants it: in groups of three digits from five digits on."""
    return f'{value:_}' if value >= 10000 else str(value)


def cell_of(data):
    """The plane, row, and cell (from 1) of a two-byte Shift_JIS-2004 sequence, as CPython's decoder computes them."""
    c, c2 = data
    c1 = c - 0x81 if c < 0xE0 else c - 0xC1
    c2 = c2 - 0x40 if c2 < 0x80 else c2 - 0x41
    c1 = 2 * c1 + (0 if c2 < 0x5E else 1)
    c2 = (c2 if c2 < 0x5E else c2 - 0x5E) + 0x21
    if c1 < 0x5E:
        return 1, c1 + 0x21 - 0x20, c2 - 0x20
    if c1 >= 0x67:
        c1 += 0x07
    elif c1 >= 0x63 or c1 == 0x5F:
        c1 -= 0x37
    else:
        c1 -= 0x3D
    return 2, c1 - 0x20, c2 - 0x20


planes = {1: {}, 2: {}}
for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
    for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
        data = bytes([lead, trail])
        try:
            text = data.decode('shift_jis_2004')
        except UnicodeDecodeError:
            continue
        plane, row, cell = cell_of(data)
        assert 1 <= row <= 94 and 1 <= cell <= 94, (data, plane, row, cell)
        planes[plane][(row, cell)] = text

encoded = {}
for point in range(0x110000):
    if 0xD800 <= point < 0xE000:
        continue
    try:
        data = chr(point).encode('shift_jis_2004')
    except UnicodeEncodeError:
        continue
    if len(data) == 1:
        # JIS X 0201, which the encoder tries before JIS X 0213.
        continue
    encoded[point] = cell_of(data)

# The rule the TypeScript side follows: the last cell of plane 1, then of plane 2, that decodes to a character alone.
rule = {}
for plane in (1, 2):
    for (row, cell), text in sorted(planes[plane].items()):
        if len(text) == 1:
            rule[ord(text)] = (plane, row, cell)
exceptions = sorted(
    (point, encoded.get(point)) for point in set(encoded) | set(rule) if encoded.get(point) != rule.get(point)
)

pairs = sorted(((text, key) for key, text in planes[1].items() if len(text) == 2))
assert not any(len(text) == 2 for text in planes[2].values())


def plane_text(plane):
    rows = []
    for row in range(1, 95):
        chars = []
        for cell in range(1, 95):
            text = planes[plane].get((row, cell), UNASSIGNED)
            chars.append(text if len(text) == 1 else UNASSIGNED)
        rows.append(''.join(chars))
    return rows


def escaped(text):
    out = []
    for char in text:
        point = ord(char)
        if char in "'\\" or not char.isprintable() or 0xE000 <= point < 0xF900 or point >= 0xFFF0 and point <= 0xFFFF:
            out.append(f'\\u{point:04X}' if point < 0x10000 else f'\\u{{{point:X}}}')
        else:
            out.append(char)
    return ''.join(out)


out = sys.stdout
out.write('// Generated by scripts/pythonData/generateJisX0213.py from CPython 3.14; do not edit.\n')
out.write('// Each plane holds 94 rows of 94 cells, U+FFFF standing for a cell that decodes to nothing.\n\n')
for plane in (1, 2):
    out.write(f'/** Plane {plane} of JIS X 0213:2004, with JIS X 0208 in plane 1, as shift_jis_2004 decodes it. */\n')
    out.write(f'export const JIS_X_0213_PLANE_{plane} = [\n')
    for text in plane_text(plane):
        out.write(f"  '{escaped(text)}',\n")
    out.write("].join('');\n\n")
out.write('/** The cells of plane 1 that decode to a character and a combining one, by row and cell. */\n')
out.write('export const JIS_X_0213_PAIRS: [number, number, string][] = [\n')
for text, (row, cell) in pairs:
    out.write(f"  [{row}, {cell}, '{escaped(text)}'],\n")
out.write('];\n\n')
out.write('/**\n * The characters that do not encode to the last cell that decodes to them: the plane, row, and cell they encode\n')
out.write(' * to, or none for a character the codec cannot encode.\n */\n')
out.write('export const JIS_X_0213_ENCODINGS: [number, number, number, number][] = [\n')
for point, where in exceptions:
    plane, row, cell = where or (0, 0, 0)
    out.write(f'  [{number(point)}, {plane}, {row}, {cell}],\n')
out.write('];\n')
