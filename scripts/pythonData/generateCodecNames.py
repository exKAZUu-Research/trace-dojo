# Prints src/python/data/codecNames.ts:
#   mise exec -- python scripts/pythonData/generateCodecNames.py > src/python/data/codecNames.ts
import codecs, encodings, encodings.aliases, pkgutil, sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')
mods = sorted(m.name for m in pkgutil.iter_modules(encodings.__path__) if m.name not in ('aliases', '_win_cp_codecs', 'mbcs', 'oem'))
aliases = encodings.aliases.aliases
nontext = []
for m in mods:
    info = codecs.lookup(m)
    if not info._is_text_encoding:
        nontext.append(m)
# Group aliases by module
by_mod = {}
for a, m in sorted(aliases.items()):
    if m in ('mbcs', 'oem'):
        continue
    by_mod.setdefault(m, []).append(a)
lines = []
for m in mods:
    names = by_mod.get(m, [])
    lines.append(f"  {m}: '{' '.join(names)}',")
print('// Generated by scripts/pythonData/generateCodecNames.py from CPython 3.14; do not edit.')
print('/** The codec modules of CPython, each with its aliases separated by spaces. */')
print('export const CODEC_ALIASES: Record<string, string> = {')
print('\n'.join(lines))
print('};')
print()
print('/** The codecs that convert bytes to bytes or str to str, which str.encode() and bytes.decode() refuse. */')
print('export const NON_TEXT_CODECS: ReadonlySet<string> = new Set([' + ', '.join(f"'{m}'" for m in nontext) + ']);')
