# Prints src/python/modules/pythonCodecSources.ts: the sources of CPython's codecs written in Python, which this grader
# runs as they are. Run with CPython 3.14: python generatePythonCodecSources.py > src/python/modules/pythonCodecSources.ts
import os
import sysconfig

LIB = sysconfig.get_paths()['stdlib']
SOURCES = [
    ('UTF_7', 'encodings/utf_7.py'),
    ('PUNYCODE', 'encodings/punycode.py'),
    ('IDNA', 'encodings/idna.py'),
    ('UNDEFINED', 'encodings/undefined.py'),
    ('UU_CODEC', 'encodings/uu_codec.py'),
    ('QUOPRI_CODEC', 'encodings/quopri_codec.py'),
    ('QUOPRI', 'quopri.py'),
    ('STRINGPREP', 'stringprep.py'),
]


def template_literal(text):
    # String.raw keeps backslashes; only backticks and `${` need writing as substitutions.
    return 'String.raw`' + text.replace('${', "${'$'}{").replace('`', "${'`'}") + '`'


print('// Generated by scripts/pythonData/generatePythonCodecSources.py from CPython 3.14; do not edit.')
for name, path in SOURCES:
    with open(os.path.join(LIB, path), encoding='utf-8') as file:
        text = file.read()
    print()
    print(f"/** CPython's `{path}`. */")
    print(f'export const {name} = {template_literal(text)};')
