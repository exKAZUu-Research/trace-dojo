# Prints src/python/data/charmapCodecs.ts: the decoding tables of CPython's single-byte charmap codecs, such as cp1252,
# read from their encodings modules.
#   mise exec -- python scripts/pythonData/generateCharmapCodecs.py > src/python/data/charmapCodecs.ts
import encodings
import importlib
import pkgutil
import sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

LINE = 100
IDENTITY = ''.join(map(chr, range(128)))


def escaped(text):
    def char(c):
        if c.isprintable() and c not in "'\\" and ord(c) < 0xFFFE and c != ' ' or c == ' ':
            return c
        return f'\\u{ord(c):04X}'

    return ''.join(char(c) for c in text)


def literal(text):
    pieces = [escaped(text[i : i + 64]) for i in range(0, len(text), 64)]
    return ' +\n    '.join(f"'{piece}'" for piece in pieces)


modules = []
for info in sorted(pkgutil.iter_modules(encodings.__path__), key=lambda info: info.name):
    try:
        module = importlib.import_module(f'encodings.{info.name}')
    except ImportError:
        continue
    if hasattr(module, 'decoding_table'):
        modules.append((info.name, module))

for name, module in modules:
    table = module.decoding_table
    assert len(table) == 256
    # The encoder takes the last byte that decodes to a character, as codecs.charmap_build and the encoding maps do.
    last = {}
    for byte, char in enumerate(table):
        if char != '￾':
            last[ord(char)] = byte
    for point in range(0x10000):
        if 0xD800 <= point < 0xE000:
            continue
        try:
            encoded = chr(point).encode(name)
        except UnicodeEncodeError:
            encoded = None
        assert encoded == (bytes([last[point]]) if point in last else None), (name, point)

print('// Generated by scripts/pythonData/generateCharmapCodecs.py from CPython 3.14; do not edit.')
print('// Each table gives the characters bytes 0x80 to 0xFF decode to, or all 256 when bytes below 0x80 are not ASCII;')
print('// U+FFFE marks a byte that decodes to nothing. A character encodes to the last byte that decodes to it.')
print()
print('/** The decoding table of each charmap codec module. */')
print('export const CHARMAP_TABLES: Record<string, string> = {')
for name, module in modules:
    table = module.decoding_table
    text = table[128:] if table[:128] == IDENTITY else table
    print(f'  {name}:\n    {literal(text)},')
print('};')
print()
print('/** The modules that keep an encoding dict, `encoding_map`, instead of an EncodingMap from codecs.charmap_build. */')
dict_modules = [name for name, module in modules if hasattr(module, 'encoding_map')]
print('export const DICT_MAP_MODULES: ReadonlySet<string> = new Set([')
for index in range(0, len(dict_modules), 8):
    print('  ' + ' '.join(f"'{name}'," for name in dict_modules[index : index + 8]))
print(']);')
print()
print('/** The order of the keys of an `encoding_map` that does not list its characters in order. */')
print('export const ENCODING_MAP_ORDERS: Record<string, number[]> = {')
for name, module in modules:
    if hasattr(module, 'encoding_map'):
        last = {}
        for byte, char in enumerate(module.decoding_table):
            if char != '￾':
                last[ord(char)] = byte
        assert module.encoding_map == last and list(module.decoding_map) == list(range(256)), name
        assert all((value is None) == (char == '￾') for value, char in zip(module.decoding_map.values(), module.decoding_table))
        keys = list(module.encoding_map)
        if keys != sorted(keys):
            print(f'  {name}: [')
            for index in range(0, len(keys), 12):
                print('    ' + ' '.join(f'{key},' for key in keys[index : index + 12]))
            print('  ],')
print('};')
print()
print('/** The names of the codecs whose CodecInfo name differs from their module name. */')
print('export const CHARMAP_NAMES: Record<string, string> = {')
for name, module in modules:
    info_name = module.getregentry().name
    if info_name != name:
        print(f"  {name}: '{info_name}',")
print('};')
