# Prints src/python/data/sysModuleNames.ts; run it with the macOS build of CPython that the reference outputs come from:
#   mise exec -- python scripts/pythonData/generateSysModuleNames.py > src/python/data/sysModuleNames.ts
import sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')
if sys.platform != 'darwin':
    raise SystemExit(f'Expected macOS, got {sys.platform}')


def print_names(names):
    print('\n'.join(f"  '{name}'," for name in sorted(names)))


print('// Generated by scripts/pythonData/generateSysModuleNames.py from CPython 3.14.10; do not edit.')
print()
print('/** `sys.stdlib_module_names`, including the private modules. */')
print('export const SYS_STDLIB_MODULE_NAMES: readonly string[] = [')
print_names(sys.stdlib_module_names)
print('];')
print()
print('/** `sys.builtin_module_names` of the macOS build of CPython that the reference outputs come from. */')
print('export const SYS_BUILTIN_MODULE_NAMES: readonly string[] = [')
print_names(sys.builtin_module_names)
print('];')
