# Prints src/python/modules/moduleLayouts.ts from the modules of the CPython that runs it (3.14.10):
#   mise exec -- python scripts/pythonData/generateModuleLayouts.py \
#     > src/python/modules/moduleLayouts.ts && bun fmt src/python/modules/moduleLayouts.ts
# Run it from the repository root, since it reads the module list from src/python/moduleNames.ts.
import json
import re
import subprocess
import sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

DESCRIBE = """
import importlib, json, sys, types
name = sys.argv[1]
module = importlib.import_module(name)
kind = ('package' if hasattr(module, '__path__') else 'source' if hasattr(module, '__cached__')
        else 'frozen' if hasattr(module, '__file__') else 'builtin')
layout = {'kind': kind}
if module.__doc__ is None:
    layout['doc'] = False
derived = name if kind == 'package' else name.rpartition('.')[0]
if module.__package__ != derived:
    layout['package'] = module.__package__
imports = {key: value.__name__ for key, value in vars(module).items() if isinstance(value, types.ModuleType)}
if imports:
    layout['imports'] = dict(sorted(imports.items()))
layout['names'] = ' '.join(vars(module))
owners = {key: value.__module__ for key, value in vars(module).items()
          if isinstance(value, (types.FunctionType, types.BuiltinFunctionType))
          and isinstance(value.__module__, str) and value.__module__ != name}
if owners:
    layout['owners'] = owners
print(json.dumps(layout))
"""


def main():
    with open('src/python/moduleNames.ts', encoding='utf-8') as file:
        source = file.read()
    listed = re.search(r'SUPPORTED_MODULES[^\[]*\[(.*?)\]\);', source, re.S).group(1)
    modules = [name for name in re.findall(r"'([^']+)'", listed) if name != '__main__']
    print('// Generated by scripts/pythonData/generateModuleLayouts.py from CPython 3.14.10.')
    print("// oxlint-disable unicorn/no-null -- A module's __package__ may be None, which JSON writes as null.")
    print("import type { ModuleLayout } from './moduleLayout';")
    print()
    print('/** How CPython provides each module this grader implements, in a process that imports only that module. */')
    print('export const MODULE_LAYOUTS: Readonly<Record<string, ModuleLayout>> = {')
    for name in modules:
        # A module such as `this` prints when imported, before the layout.
        result = subprocess.run([sys.executable, '-I', '-c', DESCRIBE, name], capture_output=True, text=True,
                                check=True)
        print(f'  {json.dumps(name)}: {result.stdout.splitlines()[-1]},')
    print('};')


main()
