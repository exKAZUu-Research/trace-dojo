#     > src/python/data/pydocData.ts
import json

from pydoc_data.module_docs import module_docs
from pydoc_data.topics import topics


def constant(name, doc, value):
    # A list of pairs keeps the dictionary's order, which JSON objects need not.
    # ASCII only, since Bun writes the other characters of a String.raw template as escapes that it then keeps raw.
    text = json.dumps(list(value.items()), separators=(',', ':'))
    print(f'/** {doc} */')
    print(f'export const {name} =\n  {template_literal(text)};')


def template_literal(text):
    # String.raw keeps backslashes, which linters prefer to escaping them; only backticks and `${` need substitutions.
    return 'String.raw`' + text.replace('${', "${'$'}{").replace('`', "${'`'}") + '`'


print('// Generated by scripts/pythonData/generatePydocData.py from CPython 3.14.10; do not edit.')
constant('PYDOC_TOPICS', "`pydoc_data.topics.topics`: each topic's page, as JSON pairs.", topics)
constant('MODULE_DOCS', "`pydoc_data.module_docs.module_docs`: each module's documentation page, as JSON pairs.",
         module_docs)
