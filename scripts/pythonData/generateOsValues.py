# Prints src/python/data/osValues.ts; run it with the macOS build of CPython that the reference outputs come from:
#   mise exec -- python scripts/pythonData/generateOsValues.py > src/python/data/osValues.ts
import os
import sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')
if sys.platform != 'darwin':
    raise SystemExit(f'Expected macOS, got {sys.platform}')

# src/python/modules/os.ts defines these with the module's functions that take them.
DEFINED_ELSEWHERE = {'SEEK_SET', 'SEEK_CUR', 'SEEK_END'}
ERROR_COUNT = next(code for code in range(1000) if os.strerror(code) == f'Unknown error: {code}')


def string(text):
    """A string literal as Prettier writes it: in single quotes unless the text has one."""
    return f'"{text}"' if "'" in text else f"'{text}'"


def bigint(value):
    """A bigint literal as the linter wants it: in groups of three digits from five digits on."""
    return (f'{value:_}' if value >= 10000 else str(value)) + 'n'


def print_entries(name, entries):
    print(f'export const {name}: [string, bigint][] = [')
    for key, value in entries:
        print(f'  [{string(key)}, {bigint(value)}],')
    print('];')


def print_strings(texts):
    print('\n'.join(f'  {string(text)},' for text in texts))


constants = [(name, getattr(os, name)) for name in dir(os) if type(getattr(os, name)) is int]
print('// Generated by scripts/pythonData/generateOsValues.py from CPython 3.14.10 on macOS; do not edit.')
print()
print('/** The integer constants of os on the reference macOS. */')
print_entries('OS_CONSTANTS', [(name, value) for name, value in sorted(constants) if name not in DEFINED_ELSEWHERE])
print()
print_entries('CONFSTR_NAMES', os.confstr_names.items())
print_entries('PATHCONF_NAMES', os.pathconf_names.items())
print_entries('SYSCONF_NAMES', os.sysconf_names.items())
print()
print(f'/** `os.strerror` of the error numbers below {ERROR_COUNT} on macOS; the others are unknown. */')
print('export const ERROR_MESSAGES: readonly string[] = [')
print_strings(os.strerror(code) for code in range(ERROR_COUNT))
print('];')
print()
print('/** `os.__all__`. */')
print('export const OS_ALL: readonly string[] = [')
print_strings(os.__all__)
print('];')
