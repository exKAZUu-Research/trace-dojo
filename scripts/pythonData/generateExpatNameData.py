# Prints src/python/modules/xml/expatNameData.ts by parsing each non-ASCII BMP character in a name with pyexpat:
#   mise exec -- python scripts/pythonData/generateExpatNameData.py > src/python/modules/xml/expatNameData.ts
import sys
from xml.parsers import expat

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

# Surrogates have no UTF-8 encoding to parse.
CODES = [code for code in range(0x80, 0x10000) if not 0xD800 <= code <= 0xDFFF]


def accepts(document):
    try:
        expat.ParserCreate().Parse(document.encode(), True)
    except expat.ExpatError:
        return False
    return True


def ranges(test):
    result = []
    for code in CODES:
        if not test(chr(code)):
            continue
        if result and result[-1][1] == code - 1:
            result[-1][1] = code
        else:
            result.append([code, code])
    return ' '.join(f'{first:x}' if first == last else f'{first:x}-{last:x}' for first, last in result)


version = expat.EXPAT_VERSION.removeprefix('expat_')
print(f'// Generated by scripts/pythonData/generateExpatNameData.py from CPython 3.14.10 (expat {version}); do not '
      'edit.')
print('/** The non-ASCII characters below U+10000 that expat accepts at the start of a name, as hexadecimal ranges. */')
print('export const NAME_START_RANGES =')
print(f"  '{ranges(lambda char: accepts(f'<{char}/>'))}';")
print('/** The non-ASCII characters below U+10000 that expat accepts after the start of a name, as hexadecimal '
      'ranges. */')
print('export const NAME_RANGES =')
print(f"  '{ranges(lambda char: accepts(f'<a{char}/>'))}';")
