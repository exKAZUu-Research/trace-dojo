# Prints src/python/data/unicode320.ts: how CPython's unicodedata.ucd_3_2_0, the Unicode 3.2.0 database that IDNA uses,
# differs from the current one, read back from the module:
#   mise exec -- python scripts/pythonData/generateUnicode320.py > src/python/data/unicode320.ts
import sys
import unicodedata as current

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

old = current.ucd_3_2_0
LAST = 0x10FFFF
LINE = 100


def b36(number):
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    text = ''
    while True:
        number, rest = divmod(number, 36)
        text = digits[rest] + text
        if number == 0:
            return text


def number(value):
    """A number as the linter wants it: in groups of three digits from five digits on."""
    return f'{value:_}' if value >= 10000 else str(value)


def value_text(value):
    if value is None:
        return '-'
    if isinstance(value, float):
        return repr(value)
    return str(value)


def runs(get_old, get_current):
    """The runs of code points where the old value differs from the current one, with the old value."""
    result = []
    for point in range(LAST + 1):
        char = chr(point)
        before, now = get_old(char), get_current(char)
        if before == now:
            continue
        if result and result[-1][1] == point - 1 and result[-1][2] == before:
            result[-1][1] = point
        else:
            result.append([point, point, before])
    return result


def literal(name, doc, entries):
    text = ','.join(entries)
    assert "'" not in text and '\\' not in text
    chunks = [text[i : i + LINE] for i in range(0, len(text), LINE)] or ['']
    lines = [f'/** {doc} */', f'export const {name} = [']
    lines += [f"  '{chunk}'," for chunk in chunks]
    lines.append("].join('');")
    return '\n'.join(lines)


def with_default(function):
    return lambda char: function(char, None)


PROPERTIES = [
    ('CATEGORY', 'category', old.category, current.category),
    ('BIDIRECTIONAL', 'bidirectional class', old.bidirectional, current.bidirectional),
    ('COMBINING', 'canonical combining class', old.combining, current.combining),
    ('EAST_ASIAN_WIDTH', 'East Asian width', old.east_asian_width, current.east_asian_width),
    ('MIRRORED', 'mirrored property', old.mirrored, current.mirrored),
    ('DECOMPOSITION', 'decomposition', old.decomposition, current.decomposition),
    ('DECIMAL', 'decimal value', with_default(old.decimal), with_default(current.decimal)),
    ('DIGIT', 'digit value', with_default(old.digit), with_default(current.digit)),
    ('NUMERIC', 'numeric value', with_default(old.numeric), with_default(current.numeric)),
]

print('// Generated by scripts/pythonData/generateUnicode320.py from CPython 3.14; do not edit.')
print('// Each list holds runs `first.last.value` of the code points, in base 36, whose Unicode 3.2.0 value differs from the')
print('// current one; `-` stands for no value.')
for name, doc, get_old, get_current in PROPERTIES:
    found = runs(get_old, get_current)
    for _, _, value in found:
        assert '.' not in value_text(value) or isinstance(value, float), (name, value)
    entries = [f'{b36(first)}.{b36(last)}.{value_text(value)}' for first, last, value in found]
    print()
    print(literal(f'OLD_{name}', f'The runs whose Unicode 3.2.0 {doc} differs.', entries))

# Names: a character unassigned in 3.2.0 has none, and the name of every other one is the current name.
names = runs(with_default(old.name), with_default(current.name))
assert all(value is None for _, _, value in names)

# The normalization corrections of Unicode 3.2.0, which change one character's canonical decomposition.
corrections = []
for point in range(LAST + 1):
    if 0xD800 <= point < 0xE000:
        continue
    char = chr(point)
    if old.category(char) == 'Cn':
        continue
    before = old.normalize('NFD', char)
    if before != current.normalize('NFD', char) and current.decomposition(char) and old.decomposition(char):
        corrections.append(point)
print()
print('/** The characters whose Unicode 3.2.0 canonical decomposition CPython corrects, with the one it gives. */')
print('export const NORMALIZATION_CORRECTIONS: [number, number][] = [')
for point in corrections:
    decomposed = old.normalize('NFD', chr(point))
    assert len(decomposed) == 1, hex(point)
    print(f'  [{number(point)}, {number(ord(decomposed))}],')
print('];')
