import contextlib
import importlib
import io
import json
from pathlib import Path
import re
import sys

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

seen = set()
names = {}


def collect(cls):
    if not isinstance(cls, type) or cls in seen:
        return
    seen.add(cls)
    try:
        getattr(cls, '__trace_dojo_missing_attribute__')
    except AttributeError as error:
        match = re.fullmatch(r"type object '(.+)' has no attribute '__trace_dojo_missing_attribute__'", str(error))
        if match and match[1] != cls.__name__:
            names[f'{cls.__module__}.{cls.__qualname__}'] = match[1]
    for value in vars(cls).values():
        if isinstance(value, type):
            collect(value)


source = Path('src/python/moduleNames.ts').read_text()
listed = re.search(r'SUPPORTED_MODULES[^\[]*\[(.*?)\]\);', source, re.S)[1]
for name in re.findall(r"'([^']+)'", listed):
    if name == '__main__':
        continue
    with contextlib.redirect_stdout(io.StringIO()):
        module = importlib.import_module(name)
    for value in vars(module).values():
        collect(value)

print('// Generated by scripts/pythonData/generateTypeNames.py from CPython 3.14.10; do not edit.')
print('export const CPYTHON_TYPE_NAMES: Record<string, string> = ' + json.dumps(dict(sorted(names.items())), indent=2) + ';')
