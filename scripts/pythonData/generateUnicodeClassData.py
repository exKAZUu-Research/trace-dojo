import sys
import unicodedata

from unicode_runs import print_property, runs

if sys.version_info[:3] != (3, 14, 10):
    raise SystemExit(f'Expected CPython 3.14.10, got {sys.version.split()[0]}')

CLASSES = {
    'decimal': str.isdecimal,
    'digit': str.isdigit,
    'numeric': str.isnumeric,
    'alpha': str.isalpha,
    'printable': str.isprintable,
    'identifierStart': str.isidentifier,
    'identifierContinue': lambda char: ('a' + char).isidentifier(),
}


print(f'// Generated by scripts/pythonData/generateUnicodeClassData.py from CPython 3.14.10 (Unicode '
      f'{unicodedata.unidata_version}); do not edit.')
print('// Each class is runs of "gap,length" in hexadecimal: the gap from the end of the previous run, then the run\'s '
      'length.')
print('export const CLASS_DATA = {')
for name, test in CLASSES.items():
    print_property(name, runs(test))
print('};')
