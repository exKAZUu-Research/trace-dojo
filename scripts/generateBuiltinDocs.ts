// Writes src/python/data/builtinDocs.ts from the docstrings and text signatures CPython has
// (scripts/pythonData/generateBuiltinDocs.py), keeping those of what this grader implements natively:
//   bun scripts/generateBuiltinDocs.ts .tmp/builtinDocs.json
import { readFileSync, writeFileSync } from 'node:fs';

import { z } from 'zod';

import { iteratorSamples } from '../src/python/iteratorTypes';
import type { Runtime as RuntimeType } from '../src/python/runtime';
import type { PyClass as PyClassType, PyValue } from '../src/python/values';

const { parsePython } = await import('../src/python/parse');
const { runModule } = await import('../src/python/run');
const { docKey, moduleDoc } = await import('../src/python/builtinDocs');
const { SUPPORTED_MODULES } = await import('../src/python/moduleNames');
const { builtinFunctionModule } = await import('../src/python/modules');
const { Runtime } = await import('../src/python/runtime');
const { withRuntime } = await import('../src/python/runtimeContext');
const { classOf } = await import('../src/python/types');
const { UnsupportedFeatureError } = await import('../src/python/unsupported');
const { PyBuiltinFunction, PyClass, PyDescriptor } = await import('../src/python/values');

/** Values of builtin types that no module names, such as iterators, whose types the data needs. */
const SAMPLES = `${iteratorSamples.join(', ')}, {}.keys(), {}.values(), {}.items(),
(x for x in []), len, [].append, type.__dict__, sys.flags, (lambda: 0), (lambda: 0).__get__(1), (lambda: 0).__code__,
awaited, awaited.__await__(), generated, generated.asend(None), generated.athrow(ValueError), cell(), sys._getframe(),
(1).__add__, int.__add__, int.__dict__["real"], dict.__dict__["fromkeys"], sys.float_info, sys.int_info, sys.hash_info,
sys.thread_info, sys.version_info`;
/** The functions and objects that SAMPLES names. */
const SAMPLE_SETUP = `import sys, collections, struct, string, tokenize, re
async def coroutine(): pass
async def async_generator(): yield
def cell():
    x = 0
    return (lambda: x).__closure__[0]
awaited = coroutine()
generated = async_generator()`;

const reference = z
  .record(z.string(), z.tuple([z.string().nullable(), z.string().nullable()]))
  .parse(JSON.parse(readFileSync(process.argv[2] as string, 'utf8')));
const keys = new Set<string>();
const seen = new Set<PyClassType>();

for (const module of SUPPORTED_MODULES) {
  if (module === '__main__') continue;
  run(`import ${module}`, (runtime) => {
    const value = runtime.modules.get(module);
    if (!value) return;
    // A doc the data gave last time counts as none, so that the data stays the same from run to run.
    const doc = value.dict.get('__doc__');
    if (typeof doc !== 'string' || doc === moduleDoc(module)) keys.add(module);
    for (const each of value.dict.values()) collect(each);
    // The functions this grader creates in the module where CPython's come from a C accelerator.
    for (const [name, each] of value.dict) {
      const accelerator = reference[`@${module}.${name}`]?.[0];
      if (!(each instanceof PyBuiltinFunction) || accelerator === undefined) continue;
      const owner = builtinFunctionModule(runtime, each);
      if (owner === module || owner === accelerator) keys.add(`@${module}.${name}`);
    }
    // The functions this grader leaves unsupported, which pydoc documents by stand-ins.
    for (const name of value.unsupported.keys()) keys.add(`${module}.${name}`);
  });
}
run(
  `${SAMPLE_SETUP}\nsamples = [${SAMPLES}]\nawaited.close()`,
  (_runtime, globals) => {
    const samples = globals.get('samples') as { items: PyValue[] } | undefined;
    for (const sample of samples?.items ?? []) collect(classOf(sample));
  },
  true
);

const kept = Object.keys(reference)
  .filter((key) => keys.has(key))
  .toSorted();
const strings: string[] = [];
const indexes = new Map<string, number>();
const indexOf = (text: string | null): number => {
  if (text === null) return 0;
  let index = indexes.get(text);
  if (index === undefined) {
    strings.push(text);
    index = strings.length;
    indexes.set(text, index);
  }
  return index;
};
const pairs = kept.map((key) => {
  const [doc, signature] = reference[key];
  return [indexOf(doc), indexOf(signature)];
});
const data = JSON.stringify([kept, strings, pairs]);
writeFileSync(
  'src/python/data/builtinDocs.ts',
  `// Generated by scripts/generateBuiltinDocs.ts from CPython 3.14.10; do not edit.
/** The keys, the strings, and each key's docstring and text signature as indexes from 1 into the strings (0: none). */
export const BUILTIN_DOCS = ${JSON.stringify(data)};
`
);
console.log(`${kept.length} entries, ${data.length} characters`);
if (process.argv.includes('--unmatched')) {
  for (const key of [...keys].toSorted()) if (!(key in reference)) console.log(`unmatched ${key}`);
}

function collect(value: PyValue): void {
  if (value instanceof PyBuiltinFunction || value instanceof PyDescriptor) {
    addKey(value);
    return;
  }
  if (!(value instanceof PyClass) || !value.isBuiltin || seen.has(value)) return;
  seen.add(value);
  addKey(value);
  const key = docKey(value) as string;
  keys.add(`!${key}`);
  for (const [name, attribute] of value.dict) {
    if (attribute instanceof PyClass) collect(attribute);
    else if (
      attribute instanceof PyBuiltinFunction ||
      attribute instanceof PyDescriptor ||
      isAttributeDescriptor(attribute)
    )
      keys.add(`${key}.${name}`);
  }
}

function addKey(value: PyValue): void {
  try {
    const key = docKey(value);
    if (key !== undefined) keys.add(key);
  } catch {
    // A value that needs a running program to name, which the data then leaves out.
  }
}

function run(
  source: string,
  inspect: (runtime: RuntimeType, globals: Map<string, PyValue>) => void,
  required = false
): void {
  const runtime = new Runtime();
  let globals: Map<string, PyValue> | undefined;
  try {
    const result = runModule(runtime, parsePython(source), (frame) => {
      globals = frame.globals;
    });
    if (required && result.uncaughtException) throw new Error(result.uncaughtException);
  } catch (error) {
    if (required || !(error instanceof UnsupportedFeatureError)) throw error;
    return;
  }
  // Naming a builtin reads the run's state, as a function's module does.
  if (globals) withRuntime(runtime, () => inspect(runtime, globals as Map<string, PyValue>));
}

/** A getset or member descriptor, known by its owner, as importing their module first would break the import order. */
function isAttributeDescriptor(value: PyValue): boolean {
  return (value as { owner?: unknown }).owner instanceof PyClass;
}
