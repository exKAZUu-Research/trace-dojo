/** `Character.getNumericValue`: a digit's or letter's value as a digit, a numeral's value, -2, or -1. */
export function numericValueOf(code: number): number {
  let low = 0;
  let high = NUMERIC_VALUE_RUNS.length - 1;
  while (low <= high) {
    const middle = (low + high) >> 1;
    const [start, length, first, step] = NUMERIC_VALUE_RUNS[middle] as readonly [number, number, number, number];
    if (code < start) high = middle - 1;
    else if (code >= start + length) low = middle + 1;
    else return first + (code - start) * step;
  }
  return -1;
}
