export function isJdkDefined(code: number): boolean {
  let low = 0;
  let high = UNASSIGNED.length;
  while (low < high) {
    const middle = Math.floor((low + high) / 2);
    const [first, last] = UNASSIGNED[middle];
    if (code < first) high = middle;
    else if (code > last) low = middle + 1;
    else return false;
  }
  return true;
}
