export function isJdkDefined(code: number): boolean {
  return categoryOf(code) !== Category.Unassigned;
}

export function isJdkLetter(code: number): boolean {
  return categoryOf(code) === Category.Letter;
}

export function isJdkDigit(code: number): boolean {
  return categoryOf(code) === Category.Digit;
}

export function isJdkLetterOrDigit(code: number): boolean {
  const category = categoryOf(code);
  return category === Category.Letter || category === Category.Digit;
}

function categoryOf(code: number): Category | undefined {
  let low = 0;
  let high = BMP_CATEGORIES.length;
  while (low < high) {
    const middle = Math.floor((low + high) / 2);
    const [first, last, category] = BMP_CATEGORIES[middle];
    if (code < first) high = middle;
    else if (code > last) low = middle + 1;
    else return category;
  }
}
