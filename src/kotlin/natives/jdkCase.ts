export function upperJdkChar(code: number): number {
  return mappedCase(SIMPLE_UPPERCASE, code) ?? code;
}

export function lowerJdkChar(code: number): number {
  return mappedCase(SIMPLE_LOWERCASE, code) ?? code;
}

export function titleJdkChar(code: number): number {
  return mappedCase(SIMPLE_TITLECASE_DIFFERENCES, code) ?? upperJdkChar(code);
}

export function titleJdkText(code: number): string {
  // Kotlin's Char holds one UTF-16 code unit, including an unpaired surrogate.
  return TITLECASE_EXPANSIONS.get(code) ?? String.fromCodePoint(titleJdkChar(code));
}

function mappedCase(ranges: readonly CaseMapping[], code: number): number | undefined {
  const mapping = findCaseRange(ranges, code);
  return mapping && code + mapping[3];
}

function findCaseRange<T extends readonly [number, number, number, ...number[]]>(
  ranges: readonly T[],
  code: number
): T | undefined {
  let start = 0;
  let end = ranges.length;
  while (start < end) {
    const middle = (start + end) >>> 1;
    const range = ranges[middle];
    const [first, last, step] = range;
    if (code < first) end = middle;
    else if (code > last) start = middle + 1;
    else return (code - first) % step === 0 ? range : undefined;
  }
  return undefined;
}
