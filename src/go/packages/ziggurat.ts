const RN = 3.442619855899;
const RE = 7.69711747013105;

/**
 * The normal deviate of normal.go, given the draws Go makes: `j` (int32) and `i` (the table index) from one random
 * word, and `float64` for the uniform values.
 */
export function normFloat64(next: () => { j: number; i: number }, float64: () => number): number {
  for (;;) {
    const { j, i } = next();
    let x = j * WN[i];
    if (Math.abs(j) < KN[i]) return x;
    if (i === 0) {
      let logU: number;
      for (;;) {
        logU = log(float64());
        x = -logU * (1 / RN);
        const y = -log(float64());
        if (y + y >= x * x) break;
      }
      // Go fuses x's multiplication into the return's addition.
      return j > 0 ? fma(-logU, 1 / RN, RN) : fma(logU, 1 / RN, -RN);
    }
    if (fusedFloat32(Math.fround(float64()), Math.fround(FN[i - 1] - FN[i]), FN[i]) < Math.fround(exp(-0.5 * x * x))) {
      return x;
    }
  }
}

/** The exponential deviate of exp.go, given the draws Go makes: `j` (uint32) and `i` (the table index). */
export function expFloat64(next: () => { j: number; i: number }, float64: () => number): number {
  for (;;) {
    const { j, i } = next();
    const x = j * WE[i];
    if (j < KE[i]) return x;
    if (i === 0) return RE - log(float64());
    if (fusedFloat32(Math.fround(float64()), Math.fround(FE[i - 1] - FE[i]), FE[i]) < Math.fround(exp(-x))) return x;
  }
}

const float32Bits = new Float32Array(1);
const float32Words = new Uint32Array(float32Bits.buffer);

/**
 * `a*b + c` rounded once to float32, as arm64's FMADDS computes the float32 comparisons above. The product of two
 * float32 values is exact in a double, so only the sum needs care: rounding it to a double and then to float32 differs
 * from rounding once only when the double lands exactly halfway between two float32 values.
 */
function fusedFloat32(a: number, b: number, c: number): number {
  const product = a * b;
  const sum = product + c;
  const virtual = sum - product;
  const error = product - (sum - virtual) + (c - virtual);
  const rounded = Math.fround(sum);
  if (error === 0 || rounded === sum) return rounded;
  float32Bits[0] = rounded;
  float32Words[0] += rounded < sum === rounded >= 0 ? 1 : -1;
  const other = float32Bits[0];
  if (sum - rounded !== other - sum) return rounded;
  return error > 0 === other > rounded ? other : rounded;
}
