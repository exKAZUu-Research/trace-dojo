export function foldSimple(char: string): string {
  const code = char.codePointAt(0) as number;
  const mapped = exceptions.get(code);
  if (mapped !== undefined) return String.fromCodePoint(mapped);
  let left = 0;
  let right = ranges.length;
  while (left < right) {
    const middle = (left + right) >>> 1;
    const [start, end, stride, delta] = ranges[middle];
    if (code < start) right = middle;
    else if (code > end) left = middle + 1;
    else return (code - start) % stride === 0 ? String.fromCodePoint(code + delta) : char;
  }
  return char;
}

