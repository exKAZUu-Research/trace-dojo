/** Headers that exist only in other standard libraries, which clang++ with libc++ cannot find. */
const MISSING_HEADERS = new Set(['bits/stdc++.h']);

/**
 * Why a program cannot include a header, or undefined when it can: the interpreter has the standard library's headers
 * only, and the program uses what they declare at its own risk of using something the interpreter leaves out.
 */
export function headerFeature(header: string): string | undefined {
  if (STANDARD_HEADERS.has(header)) return;
  if (MISSING_HEADERS.has(header)) return `ヘッダ <${header}>（libc++ にないヘッダ）`;
  return `標準ライブラリ以外のヘッダの読み込み（#include <${header}>）`;
}
